-- ============================================================================
-- CIELO: FASE 3 - INTEGRACIÓN FICHAS, ACTIVIDADES, EVIDENCIAS Y CALIFICACIONES
-- ============================================================================
-- 1. Tablas nuevas:
--    - public.ficha_publicaciones (desacoplamiento multicurso y multiasignatura)
--    - public.docente_drive_tokens (OAuth 2.0 servidor para Google Drive)
--    - public.docente_drive_carpetas (caché O(1) de carpetas por actividad)
-- 2. Alteraciones a tablas existentes:
--    - actividades.grupo_actividad_id
--    - evidencias.calificacion_id, evidencias.drive_download_url
--    - Índice parcial contra entregas duplicadas
-- 3. Políticas RLS estrictas
-- 4. Migración idempotente de ficha_cursos existente
-- 5. Trigger de compatibilidad con ficha_cursos
-- 6. RPC docente_revisar_y_calificar_v2
-- 7. RPC portal_get_ficha_detalle_v2
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. TABLA: public.ficha_publicaciones
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ficha_publicaciones (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nota_id             UUID NOT NULL REFERENCES public.pc_notas(id) ON DELETE CASCADE,
    curso_id            BIGINT NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    asignatura          TEXT NOT NULL,
    actividad_id        BIGINT REFERENCES public.actividades(id) ON DELETE SET NULL,
    requiere_producto   BOOLEAN NOT NULL DEFAULT FALSE,
    estado              TEXT NOT NULL DEFAULT 'publicada' CHECK (estado IN ('borrador', 'publicada', 'archivada', 'revision_requerida')),
    published_by        UUID NOT NULL REFERENCES auth.users(id),
    published_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_ficha_pub_curso_asignatura UNIQUE (nota_id, curso_id, asignatura)
);

CREATE INDEX IF NOT EXISTS idx_ficha_pub_curso_asignatura ON public.ficha_publicaciones (curso_id, asignatura);
CREATE INDEX IF NOT EXISTS idx_ficha_pub_actividad ON public.ficha_publicaciones (actividad_id);
CREATE INDEX IF NOT EXISTS idx_ficha_pub_nota ON public.ficha_publicaciones (nota_id);

-- ----------------------------------------------------------------------------
-- 2. TABLA: public.docente_drive_tokens
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.docente_drive_tokens (
    user_id             UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email               TEXT NOT NULL,
    refresh_token_enc   TEXT NOT NULL,
    root_folder_id      TEXT,
    connected_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    error_estado        TEXT
);

-- ----------------------------------------------------------------------------
-- 3. TABLA: public.docente_drive_carpetas
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.docente_drive_carpetas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    curso_id            BIGINT NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    asignatura          TEXT NOT NULL,
    actividad_id        BIGINT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    drive_folder_id     TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_docente_actividad_carpeta UNIQUE (user_id, actividad_id)
);

CREATE INDEX IF NOT EXISTS idx_docente_carpetas_lookup ON public.docente_drive_carpetas (user_id, actividad_id);

-- ----------------------------------------------------------------------------
-- 4. ALTERACIONES EN TABLAS EXISTENTES
-- ----------------------------------------------------------------------------
ALTER TABLE public.actividades
    ADD COLUMN IF NOT EXISTS grupo_actividad_id UUID;

CREATE INDEX IF NOT EXISTS idx_actividades_grupo_actividad
    ON public.actividades(grupo_actividad_id)
    WHERE grupo_actividad_id IS NOT NULL;

ALTER TABLE public.evidencias
    ADD COLUMN IF NOT EXISTS calificacion_id BIGINT REFERENCES public.calificaciones(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS drive_download_url TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_evidencias_pendiente_por_actividad
    ON public.evidencias (estudiante_id, actividad_id)
    WHERE estado = 'pendiente';

-- ----------------------------------------------------------------------------
-- 5. POLÍTICAS RLS (SEGURIDAD Y AISLAMIENTO)
-- ----------------------------------------------------------------------------
ALTER TABLE public.ficha_publicaciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.docente_drive_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.docente_drive_carpetas ENABLE ROW LEVEL SECURITY;

-- ficha_publicaciones: Los docentes del curso ven publicaciones; el autor gestiona
DROP POLICY IF EXISTS ficha_pub_select_docente ON public.ficha_publicaciones;
CREATE POLICY ficha_pub_select_docente ON public.ficha_publicaciones
    FOR SELECT TO authenticated
    USING (public.is_course_teacher(curso_id));

DROP POLICY IF EXISTS ficha_pub_manage_author ON public.ficha_publicaciones;
CREATE POLICY ficha_pub_manage_author ON public.ficha_publicaciones
    FOR ALL TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.pc_notas pn
            WHERE pn.id = ficha_publicaciones.nota_id
              AND pn.usuario_id = auth.uid()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.pc_notas pn
            WHERE pn.id = ficha_publicaciones.nota_id
              AND pn.usuario_id = auth.uid()
        )
    );

-- docente_drive_tokens: Estrictamente privado por usuario autenticado
DROP POLICY IF EXISTS docente_drive_tokens_own ON public.docente_drive_tokens;
CREATE POLICY docente_drive_tokens_own ON public.docente_drive_tokens
    FOR ALL TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- docente_drive_carpetas: Privado por usuario
DROP POLICY IF EXISTS docente_drive_carpetas_own ON public.docente_drive_carpetas;
CREATE POLICY docente_drive_carpetas_own ON public.docente_drive_carpetas
    FOR ALL TO authenticated
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- ----------------------------------------------------------------------------
-- 6. TRIGGER DE COMPATIBILIDAD CON ficha_cursos (LEGACY ADAPTER)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_sync_ficha_cursos_from_publicaciones()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        INSERT INTO public.ficha_cursos (nota_id, curso_id)
        VALUES (NEW.nota_id, NEW.curso_id::INTEGER)
        ON CONFLICT (nota_id, curso_id) DO NOTHING;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        IF NOT EXISTS (
            SELECT 1 FROM public.ficha_publicaciones
            WHERE nota_id = OLD.nota_id AND curso_id = OLD.curso_id
        ) THEN
            DELETE FROM public.ficha_cursos
            WHERE nota_id = OLD.nota_id AND curso_id = OLD.curso_id::INTEGER;
        END IF;
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_ficha_cursos ON public.ficha_publicaciones;
CREATE TRIGGER trg_sync_ficha_cursos
    AFTER INSERT OR UPDATE OR DELETE ON public.ficha_publicaciones
    FOR EACH ROW
    EXECUTE FUNCTION public.trg_sync_ficha_cursos_from_publicaciones();

-- ----------------------------------------------------------------------------
-- 7. MIGRACIÓN IDEMPOTENTE Y SEGURA DE DATOS HISTÓRICOS DE ficha_cursos
-- ----------------------------------------------------------------------------
INSERT INTO public.ficha_publicaciones (
    nota_id,
    curso_id,
    asignatura,
    actividad_id,
    requiere_producto,
    estado,
    published_by
)
SELECT 
    fc.nota_id,
    fc.curso_id,
    COALESCE(act.asignatura, c.asignatura, 'general') AS asignatura,
    act.id AS actividad_id,
    COALESCE(act.requiere_producto, false) AS requiere_producto,
    CASE 
        WHEN act.cuenta_actividades > 1 THEN 'revision_requerida'
        ELSE 'publicada'
    END AS estado,
    pn.usuario_id AS published_by
FROM public.ficha_cursos fc
JOIN public.pc_notas pn ON pn.id = fc.nota_id
JOIN public.cursos c ON c.id = fc.curso_id
LEFT JOIN LATERAL (
    SELECT 
        a.id, 
        a.asignatura, 
        a.requiere_producto,
        COUNT(*) OVER() AS cuenta_actividades
    FROM public.actividades a
    WHERE a.plan_ficha_id = fc.nota_id
      AND a.curso_id = fc.curso_id
      AND a.activo IS NOT FALSE
    LIMIT 1
) act ON true
ON CONFLICT (nota_id, curso_id, asignatura) DO NOTHING;

-- ----------------------------------------------------------------------------
-- 8. RPC: docente_revisar_y_calificar_v2 (EVALUACIÓN INTEGRADA Y TRANSACCIONAL)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.docente_revisar_y_calificar_v2(
    p_evidencia_id        BIGINT,
    p_sello               INTEGER,
    p_comentario          TEXT    DEFAULT NULL,
    p_sobrescribir_manual BOOLEAN DEFAULT FALSE
)
RETURNS JSONB
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_uid          UUID := auth.uid();
    v_ev           public.evidencias;
    v_act          public.actividades;
    v_calif_previa public.calificaciones;
    v_calif_id     BIGINT;
    v_puntaje_num  NUMERIC;
BEGIN
    IF v_uid IS NULL THEN
        RETURN jsonb_build_object('error', 'Sesión no autenticada');
    END IF;

    -- Validar que el sello pertenezca al catálogo oficial de CIELO
    IF p_sello IS NULL OR p_sello NOT IN (100, 85, 70, 55, 1, 0) THEN
        RETURN jsonb_build_object('error', 'El sello seleccionado no es válido');
    END IF;

    v_puntaje_num := p_sello::NUMERIC;

    -- Obtener la evidencia comprobando permisos de curso y asignatura
    SELECT * INTO v_ev
    FROM public.evidencias
    WHERE id = p_evidencia_id
      AND public.is_course_subject_teacher(curso_id, asignatura);

    IF NOT FOUND THEN
        RETURN jsonb_build_object('error', 'No se encontró la evidencia o careces de permisos');
    END IF;

    -- Obtener la actividad vinculada
    SELECT * INTO v_act
    FROM public.actividades
    WHERE id = v_ev.actividad_id;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('error', 'La actividad vinculada a la evidencia no existe');
    END IF;

    -- Verificar calificación oficial previa
    SELECT * INTO v_calif_previa
    FROM public.calificaciones
    WHERE estudiante_id = v_ev.estudiante_id
      AND actividad_id = v_ev.actividad_id;

    -- Protección contra sobrescritura accidental de notas manuales
    IF FOUND AND v_calif_previa.puntaje IS NOT NULL AND v_calif_previa.puntaje != v_puntaje_num AND NOT p_sobrescribir_manual THEN
        RETURN jsonb_build_object(
            'requiere_confirmacion', true,
            'nota_actual', v_calif_previa.puntaje,
            'nuevo_sello', v_puntaje_num,
            'mensaje', 'Ya existe una calificación previa (' || v_calif_previa.puntaje || '). ¿Deseas reemplazarla por el sello (' || v_puntaje_num || ')?'
        );
    END IF;

    -- 1. Actualizar la Evidencia
    UPDATE public.evidencias
       SET estado       = 'revisada',
           sello        = p_sello,
           comentario   = NULLIF(btrim(COALESCE(p_comentario, '')), ''),
           revisado_por = v_uid,
           revisado_at  = NOW(),
           updated_at   = NOW()
     WHERE id = p_evidencia_id;

    -- 2. Transacción Atómica: UPSERT en public.calificaciones
    INSERT INTO public.calificaciones (
        user_id,
        estudiante_id,
        actividad_id,
        curso_id,
        periodo,
        asignatura,
        puntaje,
        competencias,
        descriptores,
        recuperacion,
        activo
    ) VALUES (
        v_uid,
        v_ev.estudiante_id,
        v_ev.actividad_id,
        v_ev.curso_id,
        COALESCE(v_act.periodo, 'P1'),
        COALESCE(v_ev.asignatura, v_act.asignatura),
        v_puntaje_num,
        COALESCE(v_act.bc_asignados, ARRAY['BC1']::TEXT[]),
        CASE WHEN v_act.indicador IS NOT NULL THEN ARRAY[v_act.indicador] ELSE '{}'::TEXT[] END,
        NULL,
        TRUE
    )
    ON CONFLICT (estudiante_id, actividad_id)
    DO UPDATE SET
        puntaje      = EXCLUDED.puntaje,
        competencias = CASE 
                         WHEN array_length(public.calificaciones.competencias, 1) > 0 THEN public.calificaciones.competencias 
                         ELSE EXCLUDED.competencias 
                       END,
        descriptores = CASE 
                         WHEN array_length(public.calificaciones.descriptores, 1) > 0 THEN public.calificaciones.descriptores 
                         ELSE EXCLUDED.descriptores 
                       END,
        user_id      = EXCLUDED.user_id,
        periodo      = EXCLUDED.periodo,
        asignatura   = EXCLUDED.asignatura,
        activo       = TRUE
    RETURNING id INTO v_calif_id;

    -- Enlazar calificacion_id en la evidencia
    UPDATE public.evidencias
       SET calificacion_id = v_calif_id
     WHERE id = p_evidencia_id;

    RETURN jsonb_build_object(
        'ok', true,
        'evidencia_id', p_evidencia_id,
        'calificacion_id', v_calif_id,
        'puntaje_oficial', v_puntaje_num,
        'estado', 'revisada'
    );
END;
$$;

-- ----------------------------------------------------------------------------
-- 9. RPC: portal_get_ficha_detalle_v2
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.portal_get_ficha_detalle_v2(
    p_session_token UUID,
    p_nota_id       UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_est         public.estudiantes;
    v_compartida  BOOLEAN;
    v_pn          public.pc_notas;
BEGIN
    v_est := public.evidencia_estudiante_del_portal(p_session_token);
    IF v_est IS NULL THEN
        RETURN jsonb_build_object('error', 'Sesión inválida');
    END IF;

    -- Verificar que la ficha esté publicada para el curso del estudiante
    SELECT EXISTS (
        SELECT 1
        FROM public.ficha_publicaciones fp
        WHERE fp.nota_id = p_nota_id
          AND fp.curso_id = v_est.curso_id
          AND fp.estado = 'publicada'
    ) OR EXISTS (
        SELECT 1
        FROM public.ficha_cursos fc
        WHERE fc.nota_id = p_nota_id
          AND fc.curso_id = v_est.curso_id
    ) INTO v_compartida;

    IF NOT v_compartida THEN
        RETURN jsonb_build_object('error', 'Ficha no disponible para este curso');
    END IF;

    SELECT * INTO v_pn FROM public.pc_notas WHERE id = p_nota_id;

    RETURN jsonb_build_object(
        'id',            v_pn.id,
        'titulo',        v_pn.titulo,
        'contenido_json', v_pn.contenido_json,
        'actualizado_en', v_pn.actualizado_en,
        -- Actividades de esta ficha que piden producto exclusivamente en el curso del estudiante
        'actividades', COALESCE((
            SELECT jsonb_agg(
                jsonb_build_object(
                    'actividad_id',   a.id,
                    'actividad',      COALESCE(a.nombre, 'Actividad'),
                    'asignatura',     COALESCE(a.asignatura, c.asignatura),
                    'fecha',          a.fecha,
                    'periodo',        a.periodo,
                    'indicador',      a.indicador,
                    'producto',       a.producto,
                    'requiere_producto', TRUE,
                    'entregado',      (
                                        SELECT COUNT(*) > 0
                                        FROM public.evidencias e
                                        WHERE e.estudiante_id = v_est.id
                                          AND e.actividad_id = a.id
                                      ),
                    'entregas',       (
                                        SELECT COALESCE(jsonb_agg(
                                            jsonb_build_object(
                                                'id',           e.id,
                                                'nombre',       e.nombre,
                                                'origen',       e.origen,
                                                'created_at',   e.created_at,
                                                'drive_url',    e.drive_url,
                                                'storage_path', e.storage_path,
                                                'estado',       e.estado,
                                                'sello',        e.sello
                                            )
                                            ORDER BY e.created_at DESC
                                        ), '[]'::JSONB)
                                        FROM public.evidencias e
                                        WHERE e.estudiante_id = v_est.id
                                          AND e.actividad_id = a.id
                                      )
                )
                ORDER BY a.fecha DESC NULLS LAST, a.id DESC
            )
            FROM public.actividades a
            JOIN public.cursos c ON c.id = a.curso_id
            WHERE a.plan_ficha_id = p_nota_id
              AND a.curso_id = v_est.curso_id
              AND a.activo IS NOT FALSE
              AND a.requiere_producto IS TRUE
        ), '[]'::JSONB)
    );
END;
$$;

