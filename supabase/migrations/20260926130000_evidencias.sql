-- ============================================================================
-- EVIDENCIAS — Portafolio del estudiante + bandeja docente
-- ============================================================================
-- QUE EXISTE Y SE REUTILIZA (nada de esto se duplica)
-- ----------------------------------------------------------------------------
--   estudiantes        dueño del trabajo. NO tiene user_id ni centro_id, asi que
--                      la identidad del estudiante en el Portal SIEMPRE llega
--                      por portal_accesos.estudiante_id.
--   actividades        la "Actividad/Ficha" que ya usan Agenda, Rubrica, Cotejo
--                      y Sellos. Trae curso_id, asignatura, fecha, periodo y
--                      plan_ficha_id -> pc_notas(id). Una evidencia cuelga de
--                      ESA fila: no se crea una tabla de actividades nueva ni se
--                      duplica la ficha.
--   pc_notas           el titulo de la ficha, reached por actividades.plan_ficha_id.
--   portal_accesos      acceso del estudiante (centro, pin, activo).
--   portal_sesiones     session_token -> acceso_id. Es el unico credencial que
--                      viaja desde el Portal.
--   is_course_teacher  helper de autorizacion que ya usan las politicas de
--                      actividades/cursos (fix_db_permissions.sql). Es la
--                      separacion centro -> curso -> estudiante -> evidencia.
--   SELLOS_INFO        catalogo de 6 sellos que vive en src/screens/Sellos.tsx.
--                      La columna `sello` de esta tabla NO inventa una escala
--                      nueva: acepta exactamente los mismos 6 valores, y el
--                      mismo PNG de public/sellos/ se pinta en la UI.
--
-- QUE NO EXISTE (verificado: evidences/entregas/adjuntos -> PGRST205)
-- ----------------------------------------------------------------------------
--   No hay ninguna tabla de archivos de estudiantes. `portal_get_evidencias`
--   devuelve CALIFICACIONES pedagogicas, no archivos. `tarea_docente
--   .archivos_entrega` pertenece al modulo institucional, no a los cursos.
--   Tampoco hay bucket para esto (solo hay `avatars` y `registros`).
--   Por eso esta es la unica tabla y el unico bucket que se crean.
--
-- DONDE VIVE LA SEGURIDAD
-- ----------------------------------------------------------------------------
--   El bucket `evidencias` es privado y la TABLA esta cerrada por RLS, pero hay
--   una limitacion de plataforma que conviene escribir en mayusculas en vez de
--   adornar con una propiedad que no se tiene:
--
--   El Portal NO tiene JWT: el estudiante no existe en auth.users, solo tiene un
--   session_token. Sin un backend que firme URLs no hay forma de emitir una
--   signed URL para anon, y este frontend es estatico (no llama a
--   server/server.js en ningun punto). Por eso la politica de SELECT del bucket
--   tiene que abrirse a `anon`, porque sin ella el alumnus no puede ni previsualizar
--   lo que acaba de subir.
--
--   CONSECUENCIA REAL, sin adornos: en Supabase Storage, conceder SELECT sobre
--   un bucket HABILITA EL LISTADO, no solo la lectura por clave. Es decir, quien
--   tenga la clave anon (que viaja en el bundle del frontend, o sea, es publica)
--   puede pedir la LISTA de objetos del bucket y obtener todos los nombres. El
--   nombre del objeto es un uuid v4, y ese uuid es la credencial: la garantia
--   real es "no se adivina", no "no se lista".
--
--   Que queda expuesto con esto: los archivos subidos por la via LOCAL. Las
--   evidencias de Drive NO pasan por este bucket en absoluto, asi que con Drive
--   como via principal el alcance de la exposicion se reduce a ese respaldo.
--
--   QUE HAY QUE HACER PARA CERRARLO DE VERDAD: desplegar server/ y mover la
--   lectura a createSignedUrl emitido alli, y pasar estas politicas a
--   `authenticated`. Es un cambio de dos lineas en la politica y una en el
--   cliente cuando exista ese backend. Hasta entonces, este bloque es el
--   conocimiento escrito del riesgo, no una garantia.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1) TABLA
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.evidencias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Identidad del trabajo. estudiante_id es NOT NULL: no hay evidencia huerfana.
    estudiante_id   BIGINT NOT NULL REFERENCES public.estudiantes(id) ON DELETE CASCADE,
    actividad_id    BIGINT NOT NULL REFERENCES public.actividades(id) ON DELETE CASCADE,
    -- Traido de actividades.plan_ficha_id al insertar. Nullable porque la
    -- actividad puede no estar anclada a una ficha.
    ficha_id        UUID REFERENCES public.pc_notas(id) ON DELETE SET NULL,
    -- Copia del curso/asignatura en el momento de la entrega. Sin esto, la
    -- bandeja docente tendria que deducir el curso desde la actividad, y una
    -- actividad reasignada dejaria las evidencias huerfanas de su grupo.
    curso_id        BIGINT NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    asignatura      TEXT,

    nombre          TEXT NOT NULL,
    descripcion     TEXT,

    -- Origen. `drive` queda soportado por el modelo (drive_file_id/drive_url/
    -- thumbnail_url) pero la v1 no conecta Drive: se documenta aqui para que la
    -- integracion real entre despues sin cambiar el esquema.
    origen          TEXT NOT NULL DEFAULT 'storage'
                        CHECK (origen IN ('storage','drive')),
    storage_path    TEXT,
    drive_file_id   TEXT,
    drive_url       TEXT,
    mime_type       TEXT,
    tamano_bytes    BIGINT,
    -- Miniatura servida por Drive cuando venga de ahi. Para `storage` la
    -- miniatura es el propio archivo: no se duplica el binario en otra fila.
    thumbnail_url   TEXT,

    -- Revision. Dos estados, los que pide el flujo: no se inventan estados
    -- pedagogicos nuevos. El contenido del juicio vive en `sello`.
    estado          TEXT NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente','revisada')),
    sello           INTEGER CHECK (sello IS NULL OR sello IN (100,85,70,55,1,0)),
    comentario      TEXT,
    revisado_por    UUID,
    revisado_at     TIMESTAMPTZ,
    creado_por      UUID,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Una evidencia tiene SI o un archivo de CIELO o una referencia de Drive.
    -- Nunca los dos, nunca ninguno.
    CONSTRAINT evidencias_origen_obligatorio CHECK (
        (origen = 'storage' AND storage_path IS NOT NULL)
        OR (origen = 'drive'   AND drive_file_id IS NOT NULL)
    ),
    -- Sellar marca revisada, y viceversa: no se guarda un sello en una
    -- evidencia que sigue pendiente, ni se da por revisada sin juicio.
    CONSTRAINT evidencias_revision_coherente CHECK (
        (estado = 'pendiente' AND sello IS NULL AND revisado_at IS NULL)
        OR (estado = 'revisada'  AND sello IS NOT NULL)
    )
);

-- El indice que usa la bandeja: curso + orden por fecha de la actividad.
CREATE INDEX IF NOT EXISTS evidencias_curso_actividad_idx
    ON public.evidencias (curso_id, actividad_id);
-- El indice que usa el Portafolio del estudiante.
CREATE INDEX IF NOT EXISTS evidencias_estudiante_idx
    ON public.evidencias (estudiante_id, created_at DESC);
-- Filtro de pendientes/revisadas sin recorrer todo el curso.
CREATE INDEX IF NOT EXISTS evidencias_curso_estado_idx
    ON public.evidencias (curso_id, estado);

