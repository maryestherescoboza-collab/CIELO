-- Autorizacion por curso Y asignatura, en un solo sitio.
--
-- `is_course_teacher(curso_id)` solo sabe de cursos: un co-docente de Matematica
-- que comparte curso con Lengua pasaria el filtro y podria leer (o sellar) el
-- trabajo de Lengua. Este helper baja un nivel mas y exige que ademas sea tutor
-- o que este vinculado a ESA asignatura.
--
-- Falla cerrado: si `p_asignatura` es NULL, la tercera rama no se cumple y solo
-- entra quien sea tutor. Es la eleccion segura para una columna nullable.
--
-- Es la MISMA regla que usan `docente_bandeja_evidencias` y
-- `docente_revisar_evidencia`, de modo que las RLS de la tabla y las RPC no
-- pueden discrepar: por mucho que se corrija una, la otra sigue cerrada.
CREATE OR REPLACE FUNCTION public.is_course_subject_teacher(p_curso_id BIGINT, p_asignatura TEXT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT public.is_course_teacher(p_curso_id)
       AND (
            EXISTS (
                SELECT 1 FROM public.cursos c
                WHERE c.id = p_curso_id
                  AND (c.user_id = auth.uid() OR c.is_tutor_oficial IS TRUE)
            )
            OR EXISTS (
                SELECT 1 FROM public.curso_docentes cd
                WHERE cd.curso_id = p_curso_id
                  AND cd.docente_id = auth.uid()
                  AND cd.activo IS NOT FALSE
                  AND (cd.rol = 'tutor' OR cd.es_tutor IS TRUE)
            )
            OR EXISTS (
                SELECT 1 FROM public.curso_docentes cd
                WHERE cd.curso_id = p_curso_id
                  AND cd.docente_id = auth.uid()
                  AND cd.activo IS NOT FALSE
                  AND cd.asignatura IS NOT NULL
                  AND cd.asignatura = p_asignatura
            )
       );
$$;

REVOKE ALL ON FUNCTION public.is_course_subject_teacher(BIGINT, TEXT) FROM PUBLIC, anon;

-- Docente: solo lo que hay en sus cursos Y de su asignatura. Mismo helper que el
-- resto del modulo, mismo criterio que visibleActividades en App.tsx.
DROP POLICY IF EXISTS evidencias_select_docente ON public.evidencias;
CREATE POLICY evidencias_select_docente ON public.evidencias
    FOR SELECT TO authenticated
    USING (public.is_course_subject_teacher(curso_id, asignatura));

DROP POLICY IF EXISTS evidencias_update_docente ON public.evidencias;
CREATE POLICY evidencias_update_docente ON public.evidencias
    FOR UPDATE TO authenticated
    USING (public.is_course_subject_teacher(curso_id, asignatura))
    WITH CHECK (public.is_course_subject_teacher(curso_id, asignatura));

