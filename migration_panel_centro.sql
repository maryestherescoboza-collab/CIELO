-- 3. POLÍTICAS RLS
--    (todas se crean después de que existan tareas y tarea_asignaciones)
-- ════════════════════════════════════════════════════════════════════

-- 3.1 POLÍTICAS DE TAREAS
-- Lectura: directores/administradores del centro, docentes asignados o creador
CREATE POLICY "tareas_select_centro"
ON public.tareas FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.centro_roles cr
        WHERE cr.centro_id = tareas.centro_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
    OR EXISTS (
        SELECT 1 FROM public.tarea_asignaciones ta
        WHERE ta.tarea_id = tareas.id
        AND ta.user_id = auth.uid()
        AND ta.activo
    )
    OR created_by = auth.uid()
);

-- Escritura: directores/administradores del centro o creador
CREATE POLICY "tareas_manage_centro"
ON public.tareas FOR ALL TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.centro_roles cr
        WHERE cr.centro_id = tareas.centro_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
    OR created_by = auth.uid()
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.centro_roles cr
        WHERE cr.centro_id = tareas.centro_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
    OR created_by = auth.uid()
);

-- 3.2 POLÍTICAS DE TAREA_ASIGNACIONES
-- Lectura: directores/administradores del centro o el docente asignado
CREATE POLICY "asignaciones_select_centro"
ON public.tarea_asignaciones FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.tareas t
        JOIN public.centro_roles cr ON cr.centro_id = t.centro_id
        WHERE t.id = tarea_asignaciones.tarea_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
    OR user_id = auth.uid()
);

-- Inserción: directores/administradores del centro
CREATE POLICY "asignaciones_insert_centro"
ON public.tarea_asignaciones FOR INSERT TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.tareas t
        JOIN public.centro_roles cr ON cr.centro_id = t.centro_id
        WHERE t.id = tarea_asignaciones.tarea_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
);

-- Actualización: el propio docente (completar) o el centro
CREATE POLICY "asignaciones_update_centro"
ON public.tarea_asignaciones FOR UPDATE TO authenticated
USING (
    user_id = auth.uid()
    OR EXISTS (
        SELECT 1 FROM public.tareas t
        JOIN public.centro_roles cr ON cr.centro_id = t.centro_id
        WHERE t.id = tarea_asignaciones.tarea_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
)
WITH CHECK (
    user_id = auth.uid()
    OR EXISTS (
        SELECT 1 FROM public.tareas t
        JOIN public.centro_roles cr ON cr.centro_id = t.centro_id
        WHERE t.id = tarea_asignaciones.tarea_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
);

-- Eliminación: directores/administradores del centro
CREATE POLICY "asignaciones_delete_centro"
ON public.tarea_asignaciones FOR DELETE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.tareas t
        JOIN public.centro_roles cr ON cr.centro_id = t.centro_id
        WHERE t.id = tarea_asignaciones.tarea_id
        AND cr.user_id = auth.uid()
        AND cr.rol IN ('director', 'administrador')
    )
);

